function compute_cotangent_weight(a, b)
    # a and b are edge vectors meeting at a vertex
    # Returns cotangent of the angle between a and b
    cross_ab = cross(a, b)
    norm_cross = norm(cross_ab)
    if norm_cross < 1e-10
        return 0.0  # Parallel vectors
    end
    return dot(a, b) / norm_cross
end

# coded by Mistral
function compute_quad_laplacian(mm::SimpleMesh)

    n = nvertices(mm)
    L = spzeros(n, n)

    for (quad,top) in zip(mm, mm.topology)
        # Get the 4 vertices of the quadrangle
        v1, v2, v3, v4 = Vec3.(Tuple.(quad.vertices))
        i1,i2,i3,i4 = top.indices

        # Split the quadrangle into two triangles: v1-v2-v3 and v1-v3-v4
        # Triangle 1: v1, v2, v3
        e1 = v2 - v1
        e2 = v3 - v2
        e3 = v1 - v3
        w12 = compute_cotangent_weight(e1, -e2)  # Weight for edge v1-v2
        w23 = compute_cotangent_weight(e2, -e3)  # Weight for edge v2-v3
        w31 = compute_cotangent_weight(e3, -e1)  # Weight for edge v3-v1

        # Triangle 2: v1, v3, v4
        e4 = v4 - v3
        e5 = v1 - v4
        e6 = v3 - v1
        w34 = compute_cotangent_weight(e4, -e5)  # Weight for edge v3-v4
        w41 = compute_cotangent_weight(e5, -e6)  # Weight for edge v4-v1
        w13 = compute_cotangent_weight(e6, -e4)  # Weight for edge v1-v3

        # Update Laplacian entries for Triangle 1
        L[i1, i1] += w12 + w31
        L[i2, i2] += w12 + w23
        L[i3, i3] += w23 + w31
        L[i1, i2] -= w12
        L[i2, i1] -= w12
        L[i2, i3] -= w23
        L[i3, i2] -= w23
        L[i3, i1] -= w31
        L[i1, i3] -= w31

        # Update Laplacian entries for Triangle 2
        L[i1, i1] += w41 + w13
        L[i3, i3] += w34 + w13
        L[i4, i4] += w34 + w41
        L[i1, i3] -= w13
        L[i3, i1] -= w13
        L[i3, i4] -= w34
        L[i4, i3] -= w34
        L[i4, i1] -= w41
        L[i1, i4] -= w41
    end

    return L
end

