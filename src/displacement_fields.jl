function compute_surface_gradient(phi, mm::SimpleMesh, L)
    vertices = mm.vertices
    n = length(vertices)
    grad_phi = Vector{Vec3}(undef, n)

    for i in 1:n
        grad = Vec3(0.0, 0.0, 0.0)
        for j in 1:n
            if L[i,j] != 0 && i != j
                # Compute cotangent weight for edge (i,j)
                w_ij = -L[i,j]

                # Unit vector from i to j
                e_ij = normalize(vertices[j] - vertices[i])

                # Contribution to the gradient
                grad += w_ij * (phi[j] - phi[i]) * e_ij
            end
        end
        grad_phi[i] = grad
    end

    return grad_phi
end

