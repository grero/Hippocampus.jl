"""
    solve_harmonic_scalar_field(L, p1_index, p2_index)

Fit a harmonic potential `ϕ` using the beltrami-laplace matrix L with the constraints
that ϕ(p1_index) = 0 and ϕ(p2_index) = 1
"""
function solve_harmonic_scalar_field(L, p1_index, p2_index)
    n = size(L,1)
    # L: Laplacian matrix (n x n)
    # p1_index, p2_index: Indices of the constrained vertices
    # n: Number of vertices

    # Initialize the solution vector
    phi = zeros(n)

    # Separate free and constrained indices
    free_indices = setdiff(1:n, [p1_index, p2_index])
    constrained_indices = [p1_index, p2_index]

    # Extract submatrices
    L_ff = L[free_indices, free_indices]
    L_fc = L[free_indices, constrained_indices]

    # Boundary conditions: phi(p1) = 0, phi(p2) = 1
    phi_constrained = [0.0, 1.0]

    # Solve for free variables: L_ff * phi_f + L_fc * phi_constrained = 0
    phi_f = -L_ff \ (L_fc * phi_constrained)

    # Assign the solution
    phi[free_indices] = phi_f
    phi[p1_index] = 0.0
    phi[p2_index] = 1.0

    return phi
end

