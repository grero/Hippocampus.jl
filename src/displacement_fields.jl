Integrate the derformation field `Tx` defined on the mesh `mm` for `max_steps` steps of size `step_size`
"""
function integrate_deformation_field(Tx::Vector{T}, mm, step_size=0.1, max_steps=100) where T <: GeometryBasics.Vec{N,T2} where T2 <: Real where N
    # T: Deformation field (Vec3 per vertex)
    # vertices: Original vertex positions
    # quads: List of quad elements
    n = nelements(mm)
    new_idx = fill(0, n)
    cm = Point{N,Float64}.(Tuple.(centroid.(mm)))
    # For each vertex, integrate the deformation field to find its target
    for i in 1:n
        current_point = cm[i]
        current_T = Tx[i]
        closest_j = i
        for _ in 1:max_steps
            # Move in the direction of T
            new_point = current_point + step_size * current_T

            # Find the closest vertex to new_point
            distances = [norm(new_point - cm[j]) for j in 1:n]
            closest_j = argmin(distances)

            # Stop if we're not moving or we've reached a fixed point
            if norm(current_T) < 1e-6
                break
            end

            # Update for the next iteration
            #current_point = cm[closest_j]
            current_point = new_point
            current_T = Tx[closest_j]
        end
        new_idx[i] = closest_j
    end

    return new_idx 
end